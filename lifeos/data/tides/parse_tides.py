def parse_raw_tides(raw_text):
    lines = raw_text.strip().split('\n')
    months_map = {
        'JANEIRO': 1, 'FEVEREIRO': 2, 'MARÇO': 3, 'ABRIL': 4,
        'MAIO': 5, 'JUNHO': 6, 'JULHO': 7, 'AGOSTO': 8,
        'SETEMBRO': 9, 'OUTUBRO': 10, 'NOVEMBRO': 11, 'DEZEMBRO': 12
    }
    current_month = None
    results = []
    for line in lines:
        line = line.strip()
        if not line: continue
        if line.startswith('###'):
            month_name = line.replace('###', '').strip().upper()
            current_month = months_map.get(month_name)
            continue
        if current_month is None: continue
        parts = line.split('|')
        day_str = parts[0].strip()
        try:
            day = int(day_str)
        except ValueError: continue
        events_start_idx = 1
        if any(w in parts[1].upper() for w in ['SEG', 'TER', 'QUA', 'QUI', 'SEX', 'SAB', 'SÁB', 'DOM']):
            events_start_idx = 2
        day_events = []
        for i in range(events_start_idx, len(parts)):
            event_str = parts[i].strip()
            if not event_str or '/' not in event_str: continue
            time_str, height_str = event_str.split('/')
            time_str = time_str.strip().replace(':', '')
            if len(time_str) == 4:
                time_str = f"{time_str[:2]}:{time_str[2:]}"
            else: continue
            try:
                height = float(height_str.strip())
            except ValueError: continue
            day_events.append({'time': time_str, 'height': height})
        day_events.sort(key=lambda x: x['time'])
        for i, event in enumerate(day_events):
            tide_type = 'UNKNOWN'
            if i > 0:
                tide_type = 'HIGH' if event['height'] > day_events[i-1]['height'] else 'LOW'
            elif len(day_events) > 1:
                tide_type = 'LOW' if event['height'] < day_events[1]['height'] else 'HIGH'
            date_obj = datetime.date(2026, current_month, day)
            dt_local = datetime.datetime.combine(date_obj, datetime.time.fromisoformat(event['time']))
            results.append({
                'model': 'dashboard.tideevent',
                'fields': {
                    'port_name': 'Porto de Cabedelo',
                    'date': str(date_obj),
                    'time': event['time'],
                    'datetime_local': dt_local.strftime('%Y-%m-%dT%H:%M:00'),
                    'height_m': event['height'],
                    'tide_type': tide_type,
                    'source': 'Porto de Cabedelo 2026 tide table',
                    'timezone': 'America/Fortaleza'
                }
            })
    for i in range(1, len(results)):
        if results[i]['fields']['tide_type'] == 'UNKNOWN' or results[i]['fields']['tide_type'] == results[i-1]['fields']['tide_type']:
            results[i]['fields']['tide_type'] = 'LOW' if results[i-1]['fields']['tide_type'] == 'HIGH' else 'HIGH'
    return results

